// administratorGuides replaces the long administrator guide with the short
// index and creates the four topic guides beside it, all together.
func administratorGuides(tree Tree) Outcome {
	const id = "2026-11-administrator-guides"
	files := []WholeFile{{Path: "README.md", Content: frozen(id, "README.md"), Released: releasedAdministratorGuides}}
	for _, name := range []string{"CLASSROOM.md", "INSTALLATION.md", "SOFTWARE.md", "MAINTENANCE.md"} {
		files = append(files, WholeFile{Path: name, Content: frozen(id, name), Created: true})
	}
	return ReplaceWholeFiles(tree, files)
}
